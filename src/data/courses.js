export function getTotalLessons() {
  return COURSES.reduce((sum, c) => sum + c.modules.reduce((s, m) => s + m.lessons.length, 0), 0);
}

export function getCourseLessons(course) {
  return course.modules.flatMap(m => m.lessons);
}

export function getCourseProgress(progress, courseId) {
  const p = progress[courseId];
  if (!p) return 0;
  const course = COURSES.find(c => c.id === courseId);
  if (!course) return 0;
  const total = getCourseLessons(course).length;
  return total ? Math.round((p.lessons.length / total) * 100) : 0;
}
