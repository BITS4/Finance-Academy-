export function getLevelById(id) {
  return LEVELS.find(l => l.id === id);
}

export function getLevelProgress(progress, levelId) {
  return progress?.levels?.[levelId] || {
    xp: 0,
    lessonsCompleted: [],
    interviewCompleted: false,
    gateScore: null,
    gatePassed: false,
  };
}

export function getLevelCompletionPct(progress, levelId) {
  const level = getLevelById(levelId);
  if (!level) return 0;
  const lp = getLevelProgress(progress, levelId);
  const allLessons = level.modules.flatMap(m => m.lessons);
  if (!allLessons.length) return 0;
  return Math.round((lp.lessonsCompleted.length / allLessons.length) * 100);
}

export function isLevelUnlocked(progress, levelId) {
  if (levelId === 1) return true;
  const prev = getLevelProgress(progress, levelId - 1);
  return prev.gatePassed === true;
}

export function getTotalXP(progress) {
  return progress?.totalXP || 0;
}
